#!/usr/bin/env bash

# Directory navigation
alias ..='cd ..'
alias ...='cd ../..'

# Directory history
alias -- -='cd -'
alias d='dirs -v'

# Directory operations
alias md='mkdir -p'
alias rd='rmdir'

# Directory listing
alias ls='ls -FA --color=auto'
alias l='command ls -lhA'
alias ll='command ls -lh'
alias la='command ls -lha'

alias de='cd ~/Desktop'
alias dl='cd ~/Downloads'
alias tmp='cd /tmp/tmp'
alias vi='vi -O'
alias less='/usr/bin/less -+F'
alias sshconf='vi ~/.ssh/config'
